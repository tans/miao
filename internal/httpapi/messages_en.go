// translateMessage resolves an en message; ok is false when no translation
// exists and the zh-CN source should pass through.
func translateMessage(lang, message string) (string, bool) {
	if lang == LangZH {
		return message, true
	}
	if translated, ok := messagesEN[message]; ok {
		return translated, true
	}
	if translated, ok := messagesEN2[message]; ok {
		return translated, true
	}
	for _, pattern := range patternsEN {
		if pattern.re.MatchString(message) {
			return pattern.re.ReplaceAllString(message, pattern.replacement), true
		}
	}
	return message, false
}

// interpolate replaces {name} placeholders in a localized template.
func interpolate(message string, params map[string]string) string {
	if len(params) == 0 || !strings.ContainsRune(message, '{') {
		return message
	}
	var builder strings.Builder
	for {
		start := strings.IndexByte(message, '{')
		if start < 0 {
			builder.WriteString(message)
			break
		}
		end := strings.IndexByte(message[start:], '}')
		if end < 0 {
			builder.WriteString(message)
			break
		}
		end += start
		name := message[start+1 : end]
		builder.WriteString(message[:start])
		builder.WriteString(params[name])
		message = message[end+1:]
	}
	return builder.String()
}
